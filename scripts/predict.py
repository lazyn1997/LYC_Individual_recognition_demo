def draw_bbox_results(image,
                      results,
                      input_path=None,
                      font_path="./utils/simhei.ttf",
                      save_dir=None):
    if isinstance(image, np.ndarray):
        image = Image.fromarray(image)
    width, height = image.size[0], image.size[1]
    thickness = max((width + height) // 800, 1)
    draw = ImageDraw.Draw(image)
    font_size = np.floor(2e-2 * height + 0.5).astype('int32')
    font = ImageFont.truetype(font_path, font_size, encoding="utf-8")

    color = (255, 97, 0)

    for result in results:
        # empty results
        if result["rec_docs"] is None:
            continue

        xmin, ymin, xmax, ymax = result["bbox"]
        text = "{} {:.2f}".format(result["rec_docs"], result["rec_scores"])
        th = font_size
        # 左右两端预留与线宽相同的填充
        tw = font.getsize(text)[0] + 2 * thickness

        if ymin - th > 0:
            start_y = ymin - th
        else:
            start_y = ymin + thickness
        # 画标签框
        draw.rectangle(
            [(xmin, start_y), (xmin + tw, start_y + th)], fill=color)
        # 文字左侧空出线宽大小的填充
        draw.text((xmin + thickness, start_y), text, fill=(0, 0, 0), font=font)
        # 画目标框，线条宽度为thickness
        draw.rectangle(
            [(xmin, ymin), (xmax, ymax)], outline=color, width=thickness)

    cv2.namedWindow('fish', cv2.WINDOW_NORMAL)
    cv2.setWindowProperty('fish', cv2.WND_PROP_FULLSCREEN, cv2.WINDOW_FULLSCREEN)
    cv2.imshow('fish', np.array(image)[:, :, ::-1])
    cv2.waitKey(1)

    if save_dir is not None and input_path is not None:
        image_name = os.path.basename(input_path)
        os.makedirs(save_dir, exist_ok=True)
        output_path = os.path.join(save_dir, image_name)
        image.save(output_path, quality=100)
    del draw
    return np.array(image)


